import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ENGINE_MODULES = ("selene-core", "selene-webgpu")
EXAMPLE_MODULES = ("examples", "examples-web")
CODEGEN_PIN_FILES = (
    ".github/workflows/build.yaml", "examples/moon.mod", "examples-web/moon.mod",
    "selene-codegen/README.md", "selene-core/src/ecs/README.md",
)

# Every subprocess started by the release script is recorded and simulated.
FAKE_TOOL = r'''
import json
import os
import sys
from pathlib import Path

command = [Path(sys.argv[0]).name, *sys.argv[1:]]
log = Path(os.environ["SELENE_RELEASE_LOG"])
previous = [json.loads(line) for line in log.read_text().splitlines()]
with log.open("a") as output:
    output.write(json.dumps(command) + "\n")
if command == json.loads(os.environ["SELENE_RELEASE_FAILURE"]):
    print(os.environ["SELENE_RELEASE_ERROR"], file=sys.stderr)
    sys.exit(1)
if command[0] == "moonx" and command[2:] == ["--check", "selene-codegen/main.mbt"]:
    misses = int(os.environ["SELENE_RELEASE_ASSET_MISSES"])
    if previous.count(command) < misses:
        print("Prebuilt wasm asset does not exist", file=sys.stderr)
        sys.exit(1)
if command == ["git", "ls-files", "-z", "--", "*.mbt"]:
    sources = json.loads(os.environ["SELENE_RELEASE_SOURCES"])
    sys.stdout.buffer.write(("\0".join(sources) + "\0").encode())
elif command[0] == "moonx" and len(command) == 4 and command[2] != "--check":
    Path(command[3]).write_text("// Generated by Selene codegen.\n// " + command[1] + "\n")
elif command[0] not in ("moon", "moonx"):
    sys.exit(99)
'''


class PublishTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.script = Path(__file__).resolve().parents[1] / "publish.mbtx"
        cls.moon = shutil.which("moon")

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        modules = {
            "selene-core": ("Milky2018/selene", "0.39.1"),
            "selene-webgpu": ("Milky2018/selene_webgpu", "0.39.1"),
            "selene-codegen": ("Milky2018/selene_codegen", "0.39.2"),
            "examples": ("Milky2018/selene-examples", "0.21.2"),
            "examples-web": ("Milky2018/selene-examples-web", "0.21.2"),
        }
        for module, (name, version) in modules.items():
            path = self.root / module / "moon.mod"
            path.parent.mkdir()
            path.write_text(
                f'name = "{name}"\nversion = "{version}"\n'
                'import {\n  "Milky2018/selene@0.39.1",\n'
                '  "Milky2018/selene_webgpu",\n  "other/package@1.2.3",\n}\n'
            )
        for relative in CODEGEN_PIN_FILES:
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("a") as file:
                file.write('moonx Milky2018/selene_codegen@0.39.2 "$input" "$output"\n')
        (self.root / "docs").mkdir()
        (self.root / "docs/CHANGELOG.md").write_text(
            "## [Unreleased]\n\n## [0.40.0] - 2026-11-06\n"
        )
        (self.root / "state.mbt").write_text("#selene.resource\nstruct State {}\n")
        (self.root / "state.g.mbt").write_text("// Generated by Selene codegen. DO NOT EDIT.\n")
        self.sources = ["state.mbt", "state.g.mbt"]
        self.log = self.root / "commands.jsonl"
        self.bin = self.root / "bin"
        self.bin.mkdir()
        for name in ("moon", "moonx", "git"):
            tool = self.bin / name
            tool.write_text(f"#!{sys.executable}\n" + FAKE_TOOL)
            tool.chmod(0o755)
        self.commands = []
        self.failure = None
        self.error = "command failed"
        self.asset_misses = 0

    def invoke(self, *args, exit_code=0):
        self.log.write_text("")
        env = {
            **os.environ,
            "PATH": str(self.bin) + os.pathsep + os.environ["PATH"],
            "SELENE_RELEASE_LOG": str(self.log),
            "SELENE_RELEASE_FAILURE": json.dumps(self.failure),
            "SELENE_RELEASE_ERROR": self.error,
            "SELENE_RELEASE_ASSET_MISSES": str(self.asset_misses),
            "SELENE_RELEASE_SOURCES": json.dumps(self.sources),
        }
        result = subprocess.run(
            [self.moon, "run", "--target", "wasm", "--deny-warn", str(self.script), "--", *args],
            cwd=self.root, env=env,
            capture_output=True, text=True, timeout=30,
        )
        self.commands = [tuple(json.loads(line)) for line in self.log.read_text().splitlines()]
        self.assertEqual(result.returncode, exit_code, result.stdout + result.stderr)
        return result

    def publications(self):
        return [cmd[2] for cmd in self.commands if cmd[-1] == "publish"]

    def test_beta_updates_codegen_and_pins_without_rewriting_engine_versions(self):
        engines = [self.root / module / "moon.mod" for module in ENGINE_MODULES]
        before = {path: path.read_text() for path in engines}
        self.invoke("0.40.0-beta1", "--codegen-only")
        self.assertIn('version = "0.40.0-beta1"', (self.root / "selene-codegen/moon.mod").read_text())
        for path, content in before.items():
            self.assertEqual(path.read_text(), content)
        for module in EXAMPLE_MODULES:
            text = (self.root / module / "moon.mod").read_text()
            self.assertIn('version = "0.21.2"', text)
            self.assertIn('selene@0.39.1', text)
        for relative in CODEGEN_PIN_FILES:
            self.assertIn("selene_codegen@0.40.0-beta1", (self.root / relative).read_text())
        self.assertEqual(self.publications(), ["selene-codegen"])

    def test_stable_release_publishes_codegen_and_validates_before_core_and_webgpu(self):
        self.invoke("0.40.0-beta2", "--codegen-only")
        self.invoke("0.40.0")
        self.assertEqual(self.publications(), ["selene-codegen", "selene-core", "selene-webgpu"])
        generated = ("moonx", "Milky2018/selene_codegen@0.40.0", "state.mbt", "state.g.mbt")
        check = ("moon", "check", "--target", "all", "--deny-warn")
        test = ("moon", "test", "--deny-warn")
        self.assertLess(self.commands.index(generated), self.commands.index(check))
        self.assertLess(self.commands.index(check), self.commands.index(test))
        self.assertLess(self.commands.index(test), self.commands.index(("moon", "-C", "selene-core", "publish")))
        for relative in CODEGEN_PIN_FILES:
            self.assertIn("selene_codegen@0.40.0 ", (self.root / relative).read_text())
        for module in ("selene-codegen", *ENGINE_MODULES):
            self.assertIn('version = "0.40.0"', (self.root / module / "moon.mod").read_text())
        for module in ENGINE_MODULES + EXAMPLE_MODULES:
            text = (self.root / module / "moon.mod").read_text()
            self.assertIn('"Milky2018/selene@0.40.0"', text)
            self.assertIn('"Milky2018/selene_webgpu@0.40.0"', text)
            self.assertIn('"other/package@1.2.3"', text)
            if module in EXAMPLE_MODULES:
                self.assertIn('version = "0.21.2"', text)
        self.assertIn('name = "Milky2018/selene"', (self.root / "selene-core/moon.mod").read_text())
        self.assertEqual(self.commands.count(check), 1)
        for command in self.commands:
            self.assertNotIn("info", command)
            if "fmt" in command:
                self.assertIn("--check", command)
        self.assertEqual(self.commands[-1], ("moon", "update"))

    def test_unformatted_codegen_prevents_publication(self):
        self.failure = ("moon", "-C", "selene-codegen", "fmt", ".", "--check")
        self.invoke("0.40.0-beta1", "--codegen-only", exit_code=1)
        self.assertEqual(self.publications(), [])
        self.assertIn('version = "0.39.2"', (self.root / "selene-codegen/moon.mod").read_text())

    def test_failed_codegen_tests_prevent_publication(self):
        self.failure = ("moon", "-C", "selene-codegen", "test", ".", "--deny-warn")
        self.invoke("0.40.0-beta1", "--codegen-only", exit_code=1)
        self.assertEqual(self.publications(), [])

    def test_failed_workspace_validation_stops_engine_publication(self):
        for command in (
            ("moon", "fmt", "--check"),
            ("moon", "check", "--target", "all", "--deny-warn"),
            ("moon", "test", "--deny-warn"),
        ):
            with self.subTest(command=command):
                self.failure = command
                self.invoke("0.40.0", exit_code=1)
                self.assertEqual(self.publications(), ["selene-codegen"])

    def test_cli_rejects_invalid_versions_without_running_commands(self):
        for args in (
            ["0.40.0", "--codegen-only"], ["0.40.0-beta1"],
            ["0.40.0-beta0", "--codegen-only"], ["00.40.0"],
        ):
            with self.subTest(args=args):
                self.invoke(*args, exit_code=2)
                self.assertEqual(self.commands, [])

    def test_missing_codegen_asset_leaves_existing_consumer_pins_in_place(self):
        original = {name: (self.root / name).read_text() for name in CODEGEN_PIN_FILES}
        self.failure = ("moonx", "Milky2018/selene_codegen@0.40.0-beta1", "--check", "selene-codegen/main.mbt")
        self.invoke("0.40.0-beta1", "--codegen-only", exit_code=1)
        for name, content in original.items():
            self.assertEqual((self.root / name).read_text(), content)

    def test_missing_dated_changelog_entry_prevents_publication(self):
        for heading in ("## [0.41.0] - 2026-11-06", "## [0.40.0]"):
            with self.subTest(heading=heading):
                (self.root / "docs/CHANGELOG.md").write_text(heading + "\n")
                result = self.invoke("0.40.0", exit_code=1)
                self.assertIn("Missing dated changelog entry", result.stderr)
                self.assertEqual(self.commands, [])

    def test_pin_sync_validates_every_file_before_writing(self):
        first = self.root / CODEGEN_PIN_FILES[0]
        original = first.read_text()
        (self.root / CODEGEN_PIN_FILES[-1]).write_text("missing pin\n")
        result = self.invoke("0.40.0-beta2", "--codegen-only", exit_code=1)
        self.assertIn("Missing codegen version pin", result.stderr)
        self.assertEqual(first.read_text(), original)

    def test_new_generator_regenerates_companions_before_checking_sources(self):
        self.invoke("0.40.0-beta2", "--codegen-only")
        generator = "Milky2018/selene_codegen@0.40.0-beta2"
        ready = ("moonx", generator, "--check", "selene-codegen/main.mbt")
        generate = ("moonx", generator, "state.mbt", "state.g.mbt")
        check = ("moonx", generator, "--check", "state.mbt", "state.g.mbt")
        self.assertLess(self.commands.index(ready), self.commands.index(generate))
        self.assertLess(self.commands.index(generate), self.commands.index(check))
        self.assertIn(generator, (self.root / "state.g.mbt").read_text())

    def test_wait_retries_only_a_missing_published_wasm_asset(self):
        self.asset_misses = 1
        self.invoke("0.40.0-beta1", "--codegen-only")
        ready = ("moonx", "Milky2018/selene_codegen@0.40.0-beta1", "--check", "selene-codegen/main.mbt")
        self.assertEqual(self.commands.count(ready), 2)

    def test_wait_fails_immediately_on_other_errors(self):
        self.failure = ("moonx", "Milky2018/selene_codegen@0.40.0-beta1", "--check", "selene-codegen/main.mbt")
        self.error = "checksum mismatch"
        result = self.invoke("0.40.0-beta1", "--codegen-only", exit_code=1)
        self.assertIn(self.error, result.stderr)
        self.assertEqual(self.commands.count(self.failure), 1)

    def test_source_paths_with_spaces_and_unicode_are_preserved(self):
        folder = self.root / "dir with spaces"
        folder.mkdir()
        (folder / "状态.mbt").write_text("#selene.resource\nstruct State {}\n")
        (folder / "状态.g.mbt").write_text("// Generated by Selene codegen. DO NOT EDIT.\n")
        self.sources += ["dir with spaces/状态.mbt", "dir with spaces/状态.g.mbt"]
        self.invoke("0.40.0-beta1", "--codegen-only")
        self.assertIn(
            ("moonx", "Milky2018/selene_codegen@0.40.0-beta1", *self.sources[-2:]),
            self.commands,
        )
        self.assertIn("selene_codegen@0.40.0-beta1", (folder / "状态.g.mbt").read_text())

    def test_crlf_manifests_and_changelog_can_be_released(self):
        paths = [self.root / "docs/CHANGELOG.md"]
        paths += [self.root / name / "moon.mod" for name in ("selene-codegen", *ENGINE_MODULES, *EXAMPLE_MODULES)]
        for path in paths:
            path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
        self.invoke("0.40.0")
        self.assertEqual(self.publications(), ["selene-codegen", "selene-core", "selene-webgpu"])
        self.assertIn('version = "0.40.0"', (self.root / "selene-core/moon.mod").read_text())


if __name__ == "__main__":
    unittest.main()
