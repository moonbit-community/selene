#!/usr/bin/env python3
"""Publish Selene codegen betas or a coordinated stable release."""

import re
import subprocess
import sys
import time
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent
ENGINE_MODULES = ("selene-core", "selene-webgpu")
EXAMPLE_MODULES = ("examples", "examples-web")
CODEGEN_PIN_FILES = (
    ".github/workflows/build.yaml",
    "examples/moon.mod",
    "examples-web/moon.mod",
    "selene-codegen/README.md",
    "selene-core/src/ecs/README.md",
)
VERSION_CORE = r"(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)"


def run(*args):
    print("$", *args, flush=True)
    subprocess.run(args, cwd=ROOT_DIR, check=True)


def set_version(module, version):
    path = ROOT_DIR / module / "moon.mod"
    text = re.sub(
        r'^version\s*=\s*"[^"\n]+"$', f'version = "{version}"',
        path.read_text(encoding="utf-8"), count=1, flags=re.MULTILINE,
    )
    path.write_text(text, encoding="utf-8")


def sync_engine_dependencies(version):
    for module in ENGINE_MODULES + EXAMPLE_MODULES:
        path = ROOT_DIR / module / "moon.mod"
        text = re.sub(
            r'^(\s*"Milky2018/selene(?:_webgpu)?)(?:@[^"\n]+)?"',
            lambda match: f'{match[1]}@{version}"',
            path.read_text(encoding="utf-8"), flags=re.MULTILINE,
        )
        path.write_text(text, encoding="utf-8")


def sync_codegen_pins(version):
    changes = {}
    for relative in CODEGEN_PIN_FILES:
        path = ROOT_DIR / relative
        text, count = re.subn(
            r"Milky2018/selene_codegen@[0-9][0-9A-Za-z.+-]*",
            f"Milky2018/selene_codegen@{version}",
            path.read_text(encoding="utf-8"),
        )
        if not count:
            raise RuntimeError(f"Missing codegen version pin in {relative}")
        changes[path] = text
    for path, text in changes.items():
        path.write_text(text, encoding="utf-8")


def wait_for_codegen(version):
    command = [
        "moonx", f"Milky2018/selene_codegen@{version}",
        "--check", "selene-codegen/main.mbt",
    ]
    for attempt in range(12):
        result = subprocess.run(command, cwd=ROOT_DIR, text=True, capture_output=True)
        if result.returncode == 0:
            return
        output = result.stdout + result.stderr
        if "Prebuilt wasm asset does not exist" not in output or attempt == 11:
            raise RuntimeError(output)
        print("Waiting for the published codegen Wasm asset...", flush=True)
        time.sleep(5)


def sync_generated_sources(version):
    tracked = subprocess.check_output(
        ["git", "ls-files", "-z", "--", "*.mbt"], cwd=ROOT_DIR,
    )
    sources = [path for path in tracked.decode("utf-8").split("\0") if path]
    generator = f"Milky2018/selene_codegen@{version}"
    for output in sources:
        if output.endswith(".g.mbt") and (ROOT_DIR / output).read_text(
            encoding="utf-8",
        ).startswith("// Generated by Selene codegen."):
            run("moonx", generator, output.removesuffix(".g.mbt") + ".mbt", output)
    run("moonx", generator, "--check", *sources)


def publish_codegen(version):
    run("moon", "-C", "selene-codegen", "fmt", ".", "--check")
    set_version("selene-codegen", version)
    run("moon", "update")
    run("moon", "-C", "selene-codegen", "test", ".", "--deny-warn")
    run("moon", "-C", "selene-codegen", "publish")
    wait_for_codegen(version)
    sync_codegen_pins(version)
    sync_generated_sources(version)


def publish_release(version):
    changelog = (ROOT_DIR / "docs/CHANGELOG.md").read_text(encoding="utf-8")
    heading = rf"^## \[{re.escape(version)}\] - \d{{4}}-\d{{2}}-\d{{2}}$"
    if not re.search(heading, changelog, flags=re.MULTILINE):
        raise RuntimeError(f"Missing dated changelog entry for {version}")
    publish_codegen(version)
    for module in ENGINE_MODULES:
        set_version(module, version)
    sync_engine_dependencies(version)
    run("moon", "update")
    run("moon", "fmt", "--check")
    run("moon", "check", "--target", "all", "--deny-warn")
    run("moon", "test", "--deny-warn")
    run("moon", "-C", "selene-core", "publish")
    run("moon", "-C", "selene-webgpu", "update")
    run("moon", "-C", "selene-webgpu", "publish")
    run("moon", "update")


def main():
    args = sys.argv[1:]
    if len(args) == 1 and re.fullmatch(VERSION_CORE, args[0]):
        publish_release(args[0])
    elif (
        len(args) == 2 and args[1] == "--codegen-only"
        and re.fullmatch(rf"{VERSION_CORE}-beta[1-9]\d*", args[0])
    ):
        publish_codegen(args[0])
    else:
        print("Usage: python3 publish.py <x.y.z> | <x.y.z-betaN> --codegen-only")
        raise SystemExit(2)


if __name__ == "__main__":
    main()
